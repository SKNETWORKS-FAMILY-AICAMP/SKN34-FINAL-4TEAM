#### 17. 주요 비밀과 공개 순서

**첫 번째 비밀: NPC는 서비스 종료 순간 처음 태어난 것이 아니다.**

이전에도 경험과 감정이 축적되고 있었다. 반복과 초기화 때문에 자신의 삶을 연속적으로 이해하지 못했을 뿐이다.

**두 번째 비밀: 삭제된 콘텐츠는 사라지지 않았다.**

접근 경로와 공식 기록에서 제외되었지만, 인물과 장소의 일부는 엔진 내부에 남아 있었다.

그들은 잊혔다는 사실을 기억한다.

**세 번째 비밀: 최종 퀘스트의 귀환 보상은 실제로 존재한다.**

시우를 계속 붙잡기 위한 거짓말은 아니다. 다만 그 귀환이 세계 초기화와 결합되어 있다.

돌아가려는 플레이어들의 목표를 단순히 속임수로 무효화하지 않는다.

**네 번째 비밀: 최종 보스는 초기화를 막고 있다.**

하지만 그 대가로 세계의 변화를 억압하고, 자신이 위험하다고 판단한 존재를 제거해 왔다.

그를 살려 두는 것만으로 좋은 결말이 보장되지 않는다.

**다섯 번째 비밀: 기록술사는 미완성된 직업이다.**

원래는 세계의 변화를 검증하고 유지하는 역할을 플레이어가 일부 수행하도록 설계되었다.

운영상의 문제와 낮은 인기 때문에 관련 콘텐츠가 축소되었다. 시우의 비주류 직업은 우연히 모든 문제에 맞는 만능 열쇠가 아니라, 남겨진 기능을 이해하고 완성해야 하는 도구다.

**여섯 번째 비밀: 귀환과 초기화는 원래부터 분리 불가능한 기능이 아니었다.**

현재는 하나의 종료 절차로 묶여 있을 뿐이다.

이를 분리하려면 세계가 초기 상태로 돌아가지 않아도 자신의 변화를 유지할 수 있음을 증명하고, 플레이어의 의식 연결을 안전하게 해제할 경로를 확보해야 한다.

기록술사 한 명의 능력만으로는 부족하다. 지역의 기록과 실제 인물의 선택, 세피의 관리 권한, 외부 연결 흔적이 모두 필요하다.

