#### 12. 주인공 한시우와 캐릭터 로그

- **현실 나이:** 25세.
- **캐릭터 외형:** 짙은 갈색 머리와 회색 눈. 눈에 띄지 않는 여행자 차림.
- **직업:** 기록술사.
- **초기 레벨:** 87.
- **플레이 성향:** 탐험, 수집, 퀘스트 조사, 공략 작성.
- **장점:** 관찰, 기억, 규칙의 조합, 실패 원인 분석.
- **결점:** 사람의 행동을 퀘스트 조건처럼 예측한다.
- **초기 목표:** 최종 퀘스트를 완료하고 현실로 귀환.
- **장기적인 변화:** 자신이 아는 세계를 공략하는 사람에서, 다른 사람도 미래를 선택할 수 있도록 돕는 사람으로 성장한다.

현실의 시우는 특별한 성공을 이룬 사람이 아니다.

대학을 마친 뒤 진로를 정하지 못했고, 단기 업무와 아르바이트를 병행했다. 오래 한 게임에서는 누구보다 많은 것을 알았지만, 그 지식이 현실에서 쓸모 있다고 생각하지는 않았다.

서비스 종료는 그에게 단순히 취미를 잃는 일이 아니었다.

오랫동안 잘할 수 있다고 느꼈던 공간이 사라지는 일이었다.

그래도 현실로 돌아가고 싶다.

가족과 연락을 끊고 온 것이 아니고, 처리하지 않은 생활도 남아 있다. 현실이 지옥이라서 게임 세계에 남고 싶다는 단순한 설정으로 만들지 않는다.

시우는 초반에 NPC를 이름보다 역할로 부른다.

안내 기사. 물약 상인. 전직 담당자.

이야기가 진행되면서 그 호칭이 이름으로 바뀐다.

