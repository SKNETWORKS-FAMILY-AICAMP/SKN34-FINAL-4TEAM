#### 16. 공략 지식의 활용과 한계

시우가 아는 정보는 네 종류로 나뉜다.

**직접 확인한 정보**

던전 구조, 실제로 수행한 퀘스트 조건, 사용한 아이템의 효과다. 가장 신뢰도가 높지만 현재도 같은지 확인해야 한다.

**다른 플레이어가 검증한 정보**

과거 공략 게시판에서 확인한 내용이다. 특정 서버나 시점에만 맞는 경우가 있다.

**추정한 정보**

미완성 퀘스트와 최종 지역에 대한 가설이다. 시우 자신도 확정된 사실로 취급하면 안 된다는 것을 알지만, 급할 때는 의존하려는 유혹을 느낀다.

**패치 이전 정보**

삭제된 지역과 바뀐 조건에 관한 지식이다.

서비스 종료 후 과거의 상태가 일부 돌아오면서 강력한 장점이 되지만, 서로 다른 시기의 규칙이 섞이면 오히려 혼란을 만든다.

주인공의 통쾌한 장면은 이런 지식을 실제 행동과 연결할 때 나온다.

아무도 열지 못한 문을 열고, 쓸모없다고 버린 물건의 용도를 알아내며, 보스의 강력한 공격을 정면에서 막는 대신 전투가 시작되는 조건을 바꾼다.

다만 모든 적이 게임 시절의 공격 패턴을 반복하지는 않는다.

자아를 가진 보스는 상대를 관찰하고 전략을 수정한다. 시우가 세 번 피한 공격을 네 번째에도 같은 방식으로 쓰리라는 보장은 없다.

