다른 서버의 최상위 공격대장이었다. 여러 사람의 전투를 지휘하는 능력이 뛰어나다.

그는 NPC에게 자아가 있다는 사실을 인정한다.

그럼에도 플레이어가 원치 않게 갇힌 상황에서 현실 귀환을 포기할 의무는 없다고 주장한다.

문제는 귀환 과정에서 발생할 희생을 누가 결정하느냐이다. 그는 시간이 부족하다는 이유로 다른 가능성을 충분히 검증하지 않고, 반대하는 사람을 방해물로 취급하기 시작한다.

**백은의 섭정 에드란**

아르세인 왕국의 실질적인 통치자다.

