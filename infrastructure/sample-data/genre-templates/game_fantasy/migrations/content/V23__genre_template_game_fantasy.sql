#### 15. 퀘스트와 선택의 규칙

퀘스트는 전지적인 신의 명령이 아니다.

세계의 기록과 등장인물의 요청, 플레이어의 행동을 엔진이 구조화한 정보다.

따라서 퀘스트에는 불완전한 설명이 있을 수 있다.

“도적을 제거하라”는 의뢰의 대상이 실제로는 세금을 피해 도망친 주민일 수 있고, “성물을 회수하라”는 목표가 다른 마을의 생존에 필요한 물건을 가져오는 일일 수 있다.

퀘스트 창이 뜬다고 행동이 정당해지는 것은 아니다.

퀘스트는 크게 세 종류다.

**개인 의뢰**

주민과 집단이 원하는 일을 반영한다. 의뢰인의 정보와 관점이 그대로 들어가므로 직접 확인해야 한다.

**지역 연대기**

한 지역의 역사와 갈등을 해결하는 연속 사건이다. 기존 공략과 다르게 사람들의 선택에 따라 분기한다.

**메인 연대기**

세계의 핵심 기능과 연결된 사건이다. 시우의 귀환과 초기화 절차가 여기에 속한다.

완료 보상은 남아 있지만 무한한 재화가 생성되지는 않는다.

누군가의 금고에서 돈이 지급되거나, 실제로 존재하는 장비의 소유권이 넘어오거나, 엔진의 제한된 권한이 부여되는 방식이다.

보상만 노리고 의뢰를 반복하는 방식은 더 이상 유지되지 않는다.

