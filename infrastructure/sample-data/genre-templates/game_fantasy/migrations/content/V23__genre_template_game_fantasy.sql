외형상 24세.

게임 시절에는 초보자에게 이동과 전투를 가르치던 NPC다. 레벨은 15로 고정되어 있었다.

서비스 종료 후에는 고정된 성장 제한이 사라지지만, 곧바로 강력한 기사가 되지는 않는다. 직접 훈련하고 싸우며 경험을 쌓아야 한다.

그녀는 시우가 처음부터 강하고 친숙한 사람이라고 생각한다. 반대로 시우는 그녀를 수천 번 본 안내 기능으로 기억한다.

관계의 출발점부터 서로 다르다.

이리스는 마을을 지키고 싶어 한다. 시우의 귀환을 돕더라도 자신의 주민을 희생시키는 결정에는 반대한다.

**모르칸 — 무명왕의 묘역을 지키는 기사**

외형상 40대.

게임 시절 반복해서 처치하던 레이드 보스다.

서비스 종료 후 자신이 수많은 플레이어에게 죽었던 기억 일부를 되찾는다. 시우의 움직임을 보고 그가 자신을 여러 번 죽인 사람임을 알아챈다.

처음에는 적이지만, 묘역의 진실과 왕국의 기록 조작을 조사하며 제한적으로 협력한다.

자신을 죽인 일을 가벼운 농담으로 넘기지 않는다. 시우 역시 게임이었을 때의 행동과 지금의 관계가 같을 수 없다는 사실을 받아들인다.

**리안 벨 — 연금술사이자 상점 주인**

외형상 32세.

항상 같은 물약을 팔던 NPC였다.

재고가 자동으로 채워지지 않자 직접 재료를 구하고 제조 과정을 복원해야 한다. 그녀의 생활은 세계가 현실이 되면서 생긴 경제 변화를 보여 준다.

시우는 물약 제조법이 설정상 존재한다는 것은 알지만 실제 작업을 대신할 수 없다.

**차태준 — 다른 서버의 랭커**

현실 나이 28세. 캐릭터명 ‘레온하르트’.

레벨 100의 성기사다. 최상위 장비와 뛰어난 전투 실력을 가졌다.

시우보다 강하지만 다른 서버의 사건을 경험했기 때문에 공략 지식이 항상 일치하지 않는다.

처음에는 시우의 우회를 답답하게 여기지만, 정면 돌파만으로 해결되지 않는 상황을 겪으며 협력한다.

현실에 기다리는 가족이 있어 귀환 의지가 강하다.

**세피 — 운영 권한 일부를 가진 소녀**

외형상 16세.

정체를 알 수 없는 소녀로 등장한다. 특정 문을 열고 오류 구역을 잠시 안정시킬 수 있다.

실제로는 개발 과정에서 세계 상태를 점검하기 위해 만들어진 관리 인격이다.

완전한 운영자가 아니며, 권한과 기억이 여러 조각으로 분리되어 있다. 자신이 무엇을 위해 만들어졌는지 알지 못한다.

사람이 되고 싶다는 소망보다, 자신이 내리는 결정이 자기 선택인지 주어진 기능인지 확인하고 싶어 한다.

