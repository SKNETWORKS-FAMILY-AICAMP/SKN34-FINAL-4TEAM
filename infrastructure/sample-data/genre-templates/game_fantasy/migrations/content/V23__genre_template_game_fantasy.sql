#### 18. 장편 전개 구조

**제1부 — 로그아웃 버튼이 사라졌다**

시우는 서비스 종료 후에도 남은 세계를 확인한다.

처음에는 숨겨진 이벤트라고 생각하지만 실제 고통과 NPC의 죽음을 경험하며 상황을 받아들인다.

리넨의 보호 기능이 멈추고 몬스터가 접근한다. 시우는 알고 있는 초보자 지역의 구조를 활용해 방어하지만, 기존 공략처럼 주민을 희생시키고 보상만 얻을 수는 없다.

이리스와 함께 마을을 지킨 뒤 마지막 연대기 퀘스트를 받는다.

제1부의 끝에서 그는 현실로 돌아갈 길을 찾기 위해 마을을 떠난다.

**제2부 — 공략에 없는 대답**

왕도와 벨하임으로 이동한다.

시우는 익숙한 퀘스트를 빠르게 해결하려 하지만, NPC들이 기존 선택지에 없는 요구를 한다. 경제와 운송이 멈춘 상황도 드러난다.

패치 이전의 조건을 이용해 회색 도서관의 입구를 찾고, 기록술사의 새로운 기능을 발견한다.

처음으로 다른 서버의 플레이어와 만난다.

자신만 남아 있다는 생각이 깨지며 안도하지만, 서버마다 역사가 다르다는 문제와 마주한다.

**제3부 — 나를 죽인 플레이어**

무명왕의 묘역에 들어간다.

시우는 보스의 공격을 알고 있다는 자신감으로 접근하지만, 모르칸은 이전과 다르게 싸운다.

전투 중 시우가 죽고 첫 부활 권한을 사용한다.

돌아온 뒤 그는 현실의 한 기억이 사라졌다는 사실을 발견한다. 게임 속 죽음이 자기 삶의 일부를 지운다는 공포를 느낀다.

모르칸과의 관계를 다시 정리하며, 반복되는 공략 대상에게도 경험이 남아 있었다는 사실을 받아들인다.

**제4부 — 삭제된 자들의 도시**

삭제된 지역과 퀘스트 인물들이 나타난다.

시우는 오래된 지식으로 그들을 이해할 수 있지만, 과거 패치의 설명을 진실로 믿었다가 잘못된 선택을 한다.

세피의 정체와 연대기 엔진의 존재가 드러난다.

동시에 종결자들은 최종 지역으로 가는 열쇠를 모으기 시작한다. 귀환이라는 공동 목표 아래 협력할 수 있을 것처럼 보인다.

**제5부 — 엔딩은 세계의 끝이다**

최종 퀘스트의 실제 작동 방식이 밝혀진다.

플레이어들의 의견이 갈린다.

오태경은 현실의 삶을 우선해야 한다고 주장한다. 시우도 돌아가고 싶지만, 초기화가 단순한 게임 재시작이 아니라는 사실을 알고 있다.

이리스와 주민들은 자신들의 운명이 플레이어들끼리의 회의에서 결정되는 것에 반발한다.

갈등의 중심은 착한 사람과 나쁜 사람을 가르는 일이 아니라, 누가 어떤 희생을 결정할 권한을 가지는가이다.

**제6부 — 마지막 공략을 고친다**

시우는 귀환과 초기화를 분리할 가능성을 찾는다.

한 지역의 보스만 공략하는 방식으로는 해결할 수 없다. 서로 다른 서버의 기록과 삭제된 지역, 현재 살아 있는 주민의 선택을 연결해야 한다.

그동안 도운 인물들이 각자의 역할을 맡는다.

모르칸은 과거를 증언하고, 리안은 이동과 보급을 준비하며, 이리스는 주민과 기사단을 연결한다. 차태준은 현실 귀환을 포기하지 않은 채 다른 방법을 검증하는 데 협력한다.

시우는 모든 일을 직접 확인하려다 한계에 부딪히고, 다른 사람의 판단을 기록에 포함시키는 법을 배운다.

**제7부 — 서비스는 끝났지만**

종결자들의 최종 공략과 시우의 대안이 충돌한다.

종말의 왕은 세계를 지킨다는 이유로 누구도 새로운 선택을 하지 못하게 하려 한다. 시우는 초기화와 영구 봉쇄 모두를 거부한다.

최종 해결은 엔진의 모든 기능을 파괴하는 것이 아니다.

세계 유지와 개인의 성장, 외부 접속과 종료 절차를 분리해, 주민의 삶이 플레이어의 접속 여부에 종속되지 않도록 바꾼다.

귀환 경로가 열린다.

시우는 현실로 돌아온다. 잃어버린 기억이 모두 복구되지는 않으며, 게임을 떠나 있었던 시간의 결과도 감당해야 한다.

에르다는 계속 존재한다.

이후의 접속은 주민을 반복되는 콘텐츠로 소비하는 기존 서비스로 돌아가지 않는다. 서로 다른 세계가 어떤 조건으로 만나야 하는지 새롭게 정해야 한다.

마지막 장면에서 시우는 다시 에르다에 들어간다.

이번에는 퀘스트를 받기 위해서가 아니라, 약속한 사람을 만나기 위해서다.

