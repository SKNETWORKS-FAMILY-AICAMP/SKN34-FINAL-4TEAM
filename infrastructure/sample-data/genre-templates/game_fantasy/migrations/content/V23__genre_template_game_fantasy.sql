그를 죽이면 최종 퀘스트가 진척되지만, 동시에 초기화를 막던 장치가 사라진다.

**연대기 종결 절차**

의지를 가진 악신이라기보다, 미완성 상태를 정리하기 위해 설계된 자동 처리 체계다.

주요 서사를 완결하고 플레이어를 외부로 돌려보낸 뒤, 세계를 초기 상태로 재구성한다.

엔진은 이를 복구라고 부른다.

현재 살아 있는 인물의 기억과 관계가 사라진다는 점에서, 주민들에게는 세계의 죽음이다.

