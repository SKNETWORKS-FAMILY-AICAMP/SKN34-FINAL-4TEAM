#### 5. 주요 국가와 세력

**아르세인 왕국**

인간 중심의 가장 큰 국가다.

게임 시절 메인 퀘스트의 주요 거점이었으며, 왕실과 기사단은 플레이어에게 지속적으로 임무를 제공했다.

서비스 종료 후에는 플레이어가 처리하던 몬스터 토벌과 물자 운송이 끊기면서 문제가 쌓인다.

왕국은 시우 같은 ‘귀환자’를 필요로 하지만, 그들이 세계를 끝낼 수 있는 존재라는 사실을 알게 되면 태도가 달라진다.

**새벽성회**

부활의 성소와 치유 시설을 관리하는 종교 집단이다.

플레이어의 부활은 신의 축복으로 설명되어 왔다. 성직자들은 그 힘의 실제 작동 원리를 대부분 모른다.

자동 부활 기능이 불안정해지면서 교리와 현실 사이의 충돌이 일어난다.

사람을 돕는 성직자와 권위를 유지하려는 지도부가 함께 존재한다.

**자유도시 벨하임**

상인과 장인, 여러 종족이 모이는 도시다.

경매장과 제작 시설이 집중되어 있어 게임 시절 경제의 중심이었다. 서비스 종료 후 중앙 경매 시스템이 멈추면서 직접 거래와 신용, 실제 운송이 중요해진다.

시우가 기억하는 시세는 참고가 될 뿐이다. 공급이 끊긴 식량은 희귀 장식품보다 비싸질 수 있다.

**잊힌 자들의 연맹**

삭제된 퀘스트와 지역에서 돌아온 NPC들의 집단이다.

정식 역사에서 자신들의 이름과 존재가 지워졌다는 사실을 기억한다. 기존 왕국과 성회를 불신한다.

일부는 평화롭게 정착하려 하지만, 다른 일부는 현재 세계를 자신들의 희생 위에 세워진 가짜라고 본다.

**검은 왕좌**

게임의 주요 적대 세력이다.

공식 설정에서는 세계를 멸망시키려는 어둠의 군단으로 묘사되었다. 실제로는 서로 다른 이유로 왕국과 연대기 엔진에 저항하는 세력들이 묶여 있다.

무고한 피해자만 모인 집단은 아니다. 사람을 학살하거나 세계의 혼란을 이용하는 존재도 있다.

**종결자들**

다른 서버에서 넘어온 플레이어 일부가 만든 집단이다.

메인 퀘스트를 끝내고 현실로 돌아가는 것을 최우선 목표로 삼는다.

NPC를 불쌍하게 여기더라도 자신의 가족과 현실의 삶을 포기할 수 없다고 생각한다. 시우와 가치관이 충돌하지만, 그들의 귀환 욕구 자체가 악한 것은 아니다.

