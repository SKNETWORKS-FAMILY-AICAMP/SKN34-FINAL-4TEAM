#### 9. 직업과 전직

직업은 능력을 배우고 사용하기 위한 틀이다.

전사, 기사, 도적, 사제, 마법사, 궁수 같은 기본 직업에서 시작해 여러 전직으로 나뉜다.

히든 직업도 존재하지만 이름만으로 무조건 강하지는 않다. 특정 환경에서만 유리하거나, 성장 조건이 까다롭고 장비 선택이 좁을 수 있다.

게임 시절의 대표적인 오해는 희귀한 직업이 항상 좋은 직업이라는 생각이었다.

기록술사는 그 반례로 유명했다.

전직 조건은 복잡한데 공격력이 낮고, 다른 사람의 행동을 관측해야 능력을 확보할 수 있었다. 솔로 플레이가 불편하고, 파티에서는 전문 딜러나 치유사보다 우선순위가 낮았다.

시우가 끝까지 기록술사를 유지한 이유는 가장 강해지고 싶어서가 아니었다.

다른 직업이 지나치는 흔적과 기록을 볼 수 있었기 때문이다.

이 직업은 세계가 현실이 된 뒤 새로운 가치를 얻는다. 이전에는 퀘스트용 장식으로 보였던 기록이, 사라져 가는 인물과 장소를 확인하는 증거가 된다.

---

#### 10. 기록술사의 능력과 제약

핵심 능력은 **행동 기록**과 **단회 재현**이다.

시우는 직접 관측하고 이해한 행동의 마력 구조를 기록한 뒤 한 번 재현할 수 있다.

그러나 무엇이든 복사하는 능력은 아니다.

- 행동의 시작과 끝을 충분히 관측해야 한다.
- 자신의 직업과 신체가 감당할 수 있는 구조여야 한다.
- 필요한 무기와 도구, 자원을 갖춰야 한다.
- 원래 사용자의 압도적인 능력치를 그대로 복제하지 못한다.
- 재현한 기록은 소모된다.
- 복잡한 기록은 유지 시간이 짧고 정신적 부담이 크다.

초기에는 세 개의 행동 기록을 동시에 보관할 수 있다.

전투 중 무엇을 남기고 무엇을 버릴지 결정해야 한다. 강한 공격 세 개를 저장하면 이동과 방어 수단이 사라진다.

대표 능력은 다음과 같다.

**행동 기록**

검격, 회피, 방패 방어, 특정 마법의 일부 과정을 관측해 저장한다.

**잔류 문장 판독**

지형과 물건에 남은 퀘스트 흔적을 읽는다. 과거의 모든 장면을 영상처럼 보는 능력은 아니며, 단편과 조건만 확인할 수 있다.

**기록 비교**

현재와 과거의 구조가 다른 지점을 찾아낸다.

삭제된 문, 바뀐 문장, 사라진 이름을 확인하는 데 유용하지만 무엇이 진실인지 자동으로 판단하지는 못한다.

**공동 기록**

중반에 발전하는 능력이다.

당사자의 동의와 협력을 통해 여러 사람의 행동을 하나의 연속된 작전으로 정리한다. 상대를 강제로 조종하지 않으며, 실제 행동은 각자가 수행해야 한다.

**연대기 보존**

후반의 핵심 능력이다.

사람과 장소가 겪은 변화의 기록을 세계의 유지 구조에 남긴다. 죽은 사람을 되살리거나 없었던 사건을 만들어 내지는 못한다.

시우가 강해지는 방향은 다른 직업의 모든 능력을 빼앗는 것이 아니라, 서로 다른 사람의 선택이 사라지지 않도록 연결하는 데 있다.

