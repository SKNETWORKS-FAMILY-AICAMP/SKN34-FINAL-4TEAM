#### 3. 서비스 종료 후의 세계

세계의 이름은 **에르다**다.

여섯 개의 주요 지역과 여러 부속 공간으로 이루어져 있다. 옛 문명은 대재앙으로 무너졌고, 현재의 왕국들은 그 폐허 위에서 살아간다.

게임 시절에는 지역별로 사건이 반복되었다.

초보자 마을은 일정 시간이 지나면 원래 상태로 돌아갔고, 던전의 보스는 다시 출현했다. 상인은 정해진 상품을 채웠고, 호위 퀘스트의 대상은 죽어도 다음 날 같은 장소에 서 있었다.

서비스 종료 후에는 이러한 복구가 멈춘다.

나무를 베면 그루터기가 남고, 다리가 무너지면 직접 고쳐야 한다. 상점의 물건이 팔리면 재료를 구해 다시 만들어야 한다.

NPC들은 자신이 어제 무엇을 했는지 지속적으로 기억한다.

일부는 더 이상 기억해서는 안 되는 과거까지 떠올리기 시작한다. 서로 다른 플레이어에게 반복해서 구출되었던 경험, 같은 전투에서 여러 번 죽었던 기억, 이름과 가족이 바뀐 시절의 잔상이다.

세계가 현실이 된 뒤에도 게임의 법칙은 완전히 사라지지 않는다.

레벨과 스킬, 장비 제한과 퀘스트는 남아 있다. 그러나 그 법칙을 유지하던 자동 복구와 편의 기능은 하나씩 불안정해진다.

시우에게 가장 위험한 상황은 공략을 모르는 일이 아니다.

알고 있다고 확신한 규칙이 더 이상 작동하지 않는 순간이다.

