#### 7. 종족과 생활

에르다에는 인간, 엘프, 드워프, 수인, 여러 혼혈 공동체가 존재한다.

종족은 외형과 수명, 감각, 문화적 전통에 영향을 주지만 개인의 성격과 직업을 결정하지는 않는다.

엘프라고 모두 숲을 사랑하거나, 드워프라고 모두 대장장이인 것은 아니다. 게임의 대표 이미지와 실제 사람들의 다양성 사이에서 시우의 선입견이 드러난다.

서비스 종료 후 가장 먼저 부족해지는 것은 희귀 아이템보다 일상적인 물자다.

플레이어가 반복적으로 가져오던 약초와 광석, 몬스터 부산물이 공급되지 않는다. 자동으로 채워지던 상점 재고도 줄어든다.

던전 근처의 마을은 갑자기 생계를 잃고, 플레이어에게 의존하던 호위와 운송이 중단된다.

시우는 자신이 반복 퀘스트라고 무시했던 일이 누군가의 실제 노동을 대신해 왔다는 사실을 알게 된다.

이 세계에서 사람을 살리는 공략은 보스의 약점을 찾는 것만이 아니다.

어디에서 식량을 구하고, 누가 다리를 고칠 수 있으며, 마을 사이의 거래를 어떻게 다시 연결할지도 알아야 한다.

