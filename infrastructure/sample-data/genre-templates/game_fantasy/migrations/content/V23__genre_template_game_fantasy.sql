직업 간 격차가 커졌고, 대형 업데이트마다 이전 퀘스트가 삭제되었다. 높은 자유도는 관리하기 어려운 오류를 만들었으며, 최상위 콘텐츠 위주의 보상 구조는 신규 이용자를 지치게 했다.

이용자가 줄자 서버 통합이 반복되었다.

마지막에는 다섯 개 서버만 남았고, 공식적인 후속작 발표 이후 서비스 종료가 결정되었다.

시우가 속한 서버에서는 종료 시점에 접속 중인 플레이어가 그 혼자였다.

다른 서버에도 소수의 접속자가 남아 있었지만, 시우는 그 사실을 알지 못한다.

게임의 메인 스토리는 완결되지 않았다.

최종 지역과 관련된 자료는 존재했으나 정식 업데이트는 이루어지지 않았다. 시우는 공개된 설정과 오래된 이벤트 기록, 실제 플레이에서 확인한 단서를 모아 가장 상세한 추정 공략을 작성했다.

그 공략은 정답지가 아니라 검증되지 않은 부분이 섞인 연구 기록이다.

