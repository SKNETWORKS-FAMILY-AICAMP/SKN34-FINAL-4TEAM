#### 6. 주요 지역

**초보자 마을 리넨**

시우가 처음 접속했고 마지막까지 머물렀던 마을이다.

작은 광장과 훈련장, 약초밭, 낡은 방앗간이 있다. 게임 시절에는 누구나 몇 시간 안에 떠나는 장소였다.

서비스 종료 후에는 마을을 지키던 자동 보호 기능이 멈춘다.

시우가 처음으로 공략의 효율보다 주민의 생존을 고민하게 되는 곳이다.

**왕도 아르테온**

아르세인 왕국의 수도다.

왕궁과 대성당, 길드 연합회가 모여 있다. 화려한 퀘스트의 출발점 뒤에는 노동자와 하인, 병사들의 생활이 있다.

시우는 지도와 주요 NPC의 위치를 알고 있지만, 골목에서 살아가는 사람들의 이름은 모른다.

**벨하임의 폐쇄 경매장**

게임 시절 이용자들이 물건을 사고팔던 거대한 건물이다.

자동 거래가 멈춘 뒤 창고 소유권과 보관 물품을 두고 분쟁이 발생한다. 시스템 편의 기능이 사라진 이후의 경제 문제를 보여 준다.

**무명왕의 묘역**

오래된 중급 레이드 던전이다.

시우는 보스의 공격 패턴과 숨겨진 보상을 거의 외우고 있다. 그러나 묘역의 주인이 자신의 반복된 죽음을 기억하면서 공략이 틀어지기 시작한다.

**회색 도서관**

메인 맵에서 삭제된 기록 보관 지역이다.

기록술사의 전직과 연결되어 있었지만 업데이트 과정에서 접근 경로가 사라졌다. 시우는 패치 이전의 퀘스트 조건을 통해 입구를 찾는다.

세계의 이전 상태와 삭제된 인물의 기록이 보관되어 있다.

**균열평원**

서버 통합 과정에서 서로 다른 지역이 겹치며 생긴 장소다.

같은 성의 폐허와 온전한 모습이 나란히 존재하거나, 서로 다른 역사를 가진 마을이 하나의 강을 두고 대립한다.

시우의 지식이 다른 서버 출신에게는 틀릴 수 있다는 사실을 보여 준다.

**종언의 왕좌**

미공개 최종 지역이다.

게임을 끝내는 의식이 이루어지는 장소이며, 연대기 엔진의 핵심 기능과 연결되어 있다.

최종 보스의 방처럼 보이지만 실제로는 세계의 다음 상태를 결정하는 제어 공간이다.

