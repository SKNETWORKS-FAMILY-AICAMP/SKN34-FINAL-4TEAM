게임 시절 배경 장식이었던 묘비다.

시우는 기록술사 능력으로 지워진 이름을 읽는다. 강력한 아이템을 얻는 일만큼, 이름을 다시 남기는 일이 중요한 행동으로 자리 잡는다.

**마지막 접속 시간**

