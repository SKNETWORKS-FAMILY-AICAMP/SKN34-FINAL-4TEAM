#### 8. 레벨과 능력치

레벨은 전투 경험과 마력 운용이 축적된 정도를 나타낸다.

게임 시절에는 경험치 수치가 일정 기준에 도달하면 자동으로 상승했다. 서비스 종료 후에도 기본 체계는 유지되지만, 같은 몬스터를 반복해서 사냥하는 방식의 효율이 크게 줄어든다.

한 번 죽은 개체가 자동으로 다시 나타나지 않기 때문이다.

레벨이 높다고 모든 상황에서 이기지는 않는다.

장비와 직업, 지형과 협력, 부상 상태가 중요하다. 높은 레벨의 마법사도 주문을 준비할 시간과 시야를 확보하지 못하면 위험하다.

주요 능력치는 다음과 같다.

- **근력:** 무기와 신체 동작에 필요한 힘.
- **민첩:** 이동과 반응, 정교한 조작.
- **체력:** 부상과 피로를 견디는 능력.
- **지력:** 마법 구조를 이해하고 제어하는 능력.
- **정신:** 집중과 정신적 간섭에 대한 저항.
- **동조:** 특정 능력과 세계의 규칙을 연결하는 적합성.

기록술사는 동조와 정신의 비중이 높다.

서비스 종료 직전 로그의 레벨은 87이다. 마지막 공식 최고 레벨은 100이었다.

따라서 그는 초보자가 아니지만 최상위 랭커도 아니다. 오랜 기간 플레이했어도 전투 효율이 낮은 직업과 탐사 위주의 활동 때문에 최고 수준의 전투 성능을 갖추지 못했다.

초반에는 낮은 레벨 지역에서 강한 편이지만, 최상위 레이드 개체와 다른 서버의 랭커를 정면으로 이길 수는 없다.

