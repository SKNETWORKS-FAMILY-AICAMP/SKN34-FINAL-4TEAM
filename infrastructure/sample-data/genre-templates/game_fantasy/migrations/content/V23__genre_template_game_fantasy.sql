로맨스를 포함한다면 두 사람의 관계는 이러한 재학습 위에서 천천히 발전한다.

호감도 수치를 채워 얻는 보상이 아니라, 상대의 의사를 알 수 없는 상황에서도 대화하고 선택하는 관계다.

다른 플레이어와의 갈등에서도 시우는 현실의 가족을 기다리는 사람들을 쉽게 비난할 수 없다.

그 역시 돌아가고 싶기 때문이다.

세계의 주민을 지키려는 선택이 귀환 욕구를 부정하는 방향으로 가지 않도록 한다. 그는 둘 중 하나를 당연히 희생시키기 전에 다른 길을 충분히 검증하려 한다.

