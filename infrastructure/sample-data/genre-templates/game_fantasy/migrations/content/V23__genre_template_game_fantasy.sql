#### 11. 죽음과 부활

서비스 종료 후 죽음의 의미가 바뀐다.

NPC는 죽으면 돌아오지 않는다.

이전까지 반복 출현하던 보스도 반드시 부활하지 않는다. 특정 시설이 개체를 다시 만들 수는 있지만, 새로 만들어진 존재가 이전과 같은 기억과 인격을 가진다는 보장은 없다.

플레이어에게는 제한된 부활 기능이 남아 있다.

각 플레이어는 종료 시점에 연결되어 있던 성소의 잔여 권한에 따라 부활 횟수를 가진다. 시우에게 남은 횟수는 세 번이다.

부활에는 두 가지 대가가 있다.

첫째, 남은 권한이 소모된다. 일반적인 사냥이나 레벨업으로 다시 채울 수 없다.

둘째, 현실의 자전적 기억 일부가 손실된다.

기술 지식과 게임 공략이 우선적으로 사라지는 것은 아니다. 자신의 삶에서 경험한 특정 장면과 감정의 연결이 손상된다.

가족의 이름은 기억하지만 함께 여행했던 날을 떠올리지 못할 수 있다. 사진을 보면 그 일이 있었다는 사실은 알 수 있어도, 직접 경험한 느낌은 돌아오지 않는다.

손실 범위는 사전에 정확히 선택할 수 없다.

기록술사의 능력으로 정보를 남길 수는 있지만, 적어 둔 문장이 잃어버린 경험 자체를 되살리지는 못한다.

세 번의 권한을 모두 사용한 뒤 죽으면 되돌아올 방법은 확인되지 않는다.

이 규칙은 초반에 분명하게 드러나며, 위기 때마다 새로운 부활 방법으로 무력화하지 않는다.

