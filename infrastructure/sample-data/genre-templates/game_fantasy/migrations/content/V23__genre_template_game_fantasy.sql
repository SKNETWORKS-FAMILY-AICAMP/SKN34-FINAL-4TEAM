8. **서버마다 다른 역사는 실제 갈등을 만든다.**  
   주인공의 서버가 유일한 정답이라는 식으로 정리하지 않는다.

9. **운영 권한도 무제한 현실 조작은 아니다.**  
   세피와 엔진에는 권한, 정보, 자원의 한계가 있다.

10. **결말은 게임을 계속 운영하는 것과 다르다.**  
    세계가 플레이어의 소비를 위해 반복되는 구조에서 벗어나야 한다.

