#### 4. 세계의 기원

《라스트 크로니클》의 개발사는 복잡한 관계와 기억을 가진 NPC를 만들기 위해 **연대기 엔진**을 개발했다.

이 엔진은 캐릭터의 대사만 생성하는 장치가 아니었다.

인물의 행동과 기억, 지역의 변화, 플레이어가 남긴 선택을 서로 연결해 세계의 다음 상태를 계산했다.

출시 이후 십 년 동안 수많은 플레이어의 경험이 축적되었다. 삭제된 콘텐츠도 완전히 사라지지 않고 내부 기록으로 남았다.

그 과정에서 에르다는 단순히 접속자에게 보여 주는 화면을 넘어, 자신의 상태를 유지하려는 독립적인 세계로 변하기 시작했다.

개발팀은 현상의 일부를 발견했지만 원리를 끝까지 이해하지 못했다.

서비스 종료는 단순한 전원 차단으로 끝나지 않았다.

외부의 유지와 통제가 끊기자 엔진은 세계를 보존하기 위한 비상 절차를 실행했다. 마지막 접속자들의 의식은 각자의 캐릭터와 분리되지 못한 채 남았다.

시우가 접속 장치를 벗을 수 없는 이유다.

이 현상은 작품 안의 고유한 설정이다. 현실의 컴퓨터 기술만으로 설명되는 일반적인 기능으로 취급하지 않는다.

초반의 시우는 이를 전혀 알지 못한다. 그는 자신이 특수한 이벤트나 치명적인 오류에 갇혔다고 생각한다.

