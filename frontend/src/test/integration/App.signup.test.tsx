function mockFetch(status: number) {
  return vi.fn(async (path: string) => path.endsWith('/csrf')
    ? new Response(JSON.stringify({ csrfToken: 'csrf' }))
    : new Response(null, { status: path.endsWith('/refresh') ? 401 : status }))
}

