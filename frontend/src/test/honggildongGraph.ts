const KIND = { c: '인물', l: '장소', o: '설정', r: '규칙', e: '사건' } as const
const TYPE = { c: 'character', l: 'location', o: 'object', r: 'rule', e: 'event' } as const
/** 위 카드·관계를 관계도 view-model이 받는 그래프로 바꾼다(`useWorldMapViewModel(rows, honggildongMap)`): 관계 id는 쌍마다 번호를 붙여 모두 다르다. */
export function honggildongMap() {
  const nodes = HONGGILDONG_CARDS.map(([id, name, type]) => ({ id, name, kind: KIND[type], type: TYPE[type], text: '', tags: [] as string[] }))
  const seen = new Map<string, number>()
  const links = HONGGILDONG_LINKS.map(([source, target]) => {
    const pair = source + '>' + target, n = (seen.get(pair) ?? 0) + 1
    seen.set(pair, n)
    return { id: pair + '#' + n, source, target, label: '관계', fullLabel: '관계', symmetric: false, emotion: false }
  })
  return { nodes, links, missingLinks: 0 }
}
